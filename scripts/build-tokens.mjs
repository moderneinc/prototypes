// ---------- Hand-rolled validator (no runtime deps) ----------
// Implements the subset of JSON Schema used above: type, required, properties,
// patternProperties, additionalProperties, oneOf, const, enum, minLength,
// minimum, pattern, items.

function validate(data, schema, path = "$") {
  const errors = [];

  if (schema.const !== undefined) {
    if (data !== schema.const) errors.push(`${path}: expected const ${JSON.stringify(schema.const)}, got ${JSON.stringify(data)}`);
  }
  if (schema.enum) {
    if (!schema.enum.includes(data)) errors.push(`${path}: expected one of ${schema.enum.join(", ")}, got ${JSON.stringify(data)}`);
  }
  if (schema.type) {
    const ok = checkType(data, schema.type);
    if (!ok) errors.push(`${path}: expected type ${schema.type}, got ${typeofJson(data)}`);
  }
  if (schema.minLength !== undefined && typeof data === "string" && data.length < schema.minLength) {
    errors.push(`${path}: minLength ${schema.minLength}, got ${data.length}`);
  }
  if (schema.minimum !== undefined && typeof data === "number" && data < schema.minimum) {
    errors.push(`${path}: minimum ${schema.minimum}, got ${data}`);
  }
  if (schema.pattern && typeof data === "string" && !new RegExp(schema.pattern).test(data)) {
    errors.push(`${path}: does not match pattern ${schema.pattern}`);
  }
  if (schema.oneOf) {
    const matches = schema.oneOf.filter((s) => validate(data, s, path).length === 0);
    if (matches.length !== 1) errors.push(`${path}: oneOf matched ${matches.length} schemas (expected 1)`);
  }
  if (schema.required && data && typeof data === "object") {
    for (const r of schema.required) {
      if (!(r in data)) errors.push(`${path}: missing required key '${r}'`);
    }
  }
  if (schema.properties && data && typeof data === "object" && !Array.isArray(data)) {
    for (const k of Object.keys(schema.properties)) {
      if (k in data) errors.push(...validate(data[k], schema.properties[k], `${path}.${k}`));
    }
  }
  if (schema.patternProperties && data && typeof data === "object" && !Array.isArray(data)) {
    for (const pat of Object.keys(schema.patternProperties)) {
      const re = new RegExp(pat);
      for (const k of Object.keys(data)) {
        if (re.test(k)) errors.push(...validate(data[k], schema.patternProperties[pat], `${path}.${k}`));
      }
    }
  }
  if (schema.additionalProperties === false && data && typeof data === "object" && !Array.isArray(data)) {
    const allowed = new Set([
      ...(schema.properties ? Object.keys(schema.properties) : []),
    ]);
    const patterns = (schema.patternProperties ? Object.keys(schema.patternProperties) : []).map((p) => new RegExp(p));
    for (const k of Object.keys(data)) {
      if (allowed.has(k)) continue;
      if (patterns.some((re) => re.test(k))) continue;
      errors.push(`${path}: unexpected property '${k}'`);
    }
  }
  if (schema.items && Array.isArray(data)) {
    data.forEach((item, i) => errors.push(...validate(item, schema.items, `${path}[${i}]`)));
  }
  return errors;
}

function checkType(data, type) {
  switch (type) {
    case "object":
      return data !== null && typeof data === "object" && !Array.isArray(data);
    case "array":
      return Array.isArray(data);
    case "string":
      return typeof data === "string";
    case "integer":
      return Number.isInteger(data);
    case "number":
      return typeof data === "number";
    case "boolean":
      return typeof data === "boolean";
    case "null":
      return data === null;
    default:
      return true;
  }
}

function typeofJson(d) {
  if (d === null) return "null";
  if (Array.isArray(d)) return "array";
  return typeof d;
}

// ---------- Run ----------

mkdirSync(OUT_DIR, { recursive: true });

const errors = validate(canonical, schema);
if (errors.length) {
  console.error("✗ canonical.json failed schema validation:");
  for (const e of errors) console.error("  -", e);
  process.exit(1);
}

writeFileSync(join(OUT_DIR, "canonical.json"), JSON.stringify(canonical, null, 2) + "\n");
writeFileSync(join(OUT_DIR, "canonical.schema.json"), JSON.stringify(schema, null, 2) + "\n");
console.log("✓ wrote tokens/canonical.json");
console.log("✓ wrote tokens/canonical.schema.json");

const { dtcg, figmaMap } = figmaProject(canonical);
writeFileSync(join(OUT_DIR, "dtcg.json"), JSON.stringify(dtcg, null, 2) + "\n");
